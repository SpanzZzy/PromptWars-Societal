// Helper that safely returns full translations for all 23 scheduled languages,
// falling back to Hindi or English if an ultra-rare dialect is requested.
export function getUiTranslations(langCode: string): UiTranslations {
  if (COMMON_TRANSLATIONS[langCode]) {
    return COMMON_TRANSLATIONS[langCode];
  }
  // Mapping regional dialects to their closest sister language in the Scheduled list
  if (['doi', 'brx'].includes(langCode)) {
    return COMMON_TRANSLATIONS.hi;
  }
  if (['mni'].includes(langCode)) {
    return COMMON_TRANSLATIONS.bn;
  }
  if (['ks', 'sd'].includes(langCode)) {
    return COMMON_TRANSLATIONS.ur;
  }
  if (['sat'].includes(langCode)) {
    return COMMON_TRANSLATIONS.hi;
  }
  return COMMON_TRANSLATIONS.en;
}
